/* Design lab boot: runs in <head> before first paint (after themes.js).
 * 1. picks theme / layout / mode from ?theme=&layout=&mode= or localStorage, sets <html data-theme data-layout data-mode>
 * 2. writes every theme's CSS once (switching is then just an attribute change)
 * 3. pins the app to the 09:00 replay dashboard: other routes are inert (no fetch, no error page). */
(function () {
  "use strict";
  const L = window.LAB;
  const EV = "2026wasam", TS = "1774195200";
  const HOME = `#/${EV}/dash/${TS}`;
  L.HOME = HOME; L.EV = EV; L.TS = TS;
  const ls = { get: k => { try { return localStorage.getItem(k); } catch (e) { return null; } }, set: (k, v) => { try { localStorage.setItem(k, v); } catch (e) { } } };
  L.ls = ls;
  const byId = id => L.THEMES.find(t => t.id === id);
  L.theme = byId;

  // ---------------------------------------------------------------- CSS generation
  const decl = (o, pad = "  ") => Object.entries(o || {}).map(([k, v]) => `${pad}--${k}: ${v};`).join("\n");
  const DARK_DERIVED = { sel: "color-mix(in srgb, var(--accent) 12%, transparent)", hover: "color-mix(in srgb, var(--ink) 6%, transparent)",
    "shadow-pop": "0 2px 6px rgba(0, 0, 0, .25), 0 16px 40px rgba(0, 0, 0, .4)" };
  const LIGHT_DERIVED = { sel: "color-mix(in srgb, var(--accent) 9%, transparent)", hover: "color-mix(in srgb, var(--ink) 5%, transparent)" };
  L.modes = t => [t.light && "light", t.dark && "dark"].filter(Boolean);
  L.themeCSS = function (t, S) {
    const out = [];
    const first = t.light || t.dark, firstScheme = t.light ? "light" : "dark";
    out.push(`${S} {\n  color-scheme: ${firstScheme};\n${decl(t.base)}\n${decl(first)}\n${decl(t.light ? LIGHT_DERIVED : DARK_DERIVED)}\n}`);
    if (t.light && t.dark) {
      const dk = `color-scheme: dark;\n${decl(t.dark, "    ")}\n${decl(DARK_DERIVED, "    ")}`;
      out.push(`${S}[data-mode="dark"] {\n  ${dk.replace(/\n    /g, "\n  ")}\n}`);
      out.push(`@media (prefers-color-scheme: dark) {\n  ${S}[data-mode="auto"] {\n    ${dk}\n  }\n}`);
    }
    out.push(`@media (prefers-contrast: more) {\n  ${S} { --ink-2: var(--ink); --ink-3: var(--ink); --line: var(--line-strong); --plate-ink-2: var(--plate-ink); --plate-ink-3: var(--plate-ink); }\n}`);
    if (t.rules) out.push(t.rules.trim().replace(/:T/g, S));
    return out.join("\n");
  };
  L.fontFaces = (url = f => "fonts/" + f.file) => Object.values(L.FONTS).flat().map(f =>
    `@font-face { font-family: "${f.family}"; font-style: normal; font-weight: ${f.weight};${f.stretch ? ` font-stretch: ${f.stretch};` : ""} font-display: swap; src: url("${url(f)}") format("woff2"); }`).join("\n");

  const st = document.createElement("style"); st.id = "lab-themes";
  st.textContent = `/* generated by lab-boot.js from themes.js */\n${L.fontFaces()}\n` +
    `:where(html[data-theme]) :focus-visible { outline-color: var(--focus, var(--accent)); }\n` +
    L.THEMES.map(t => L.themeCSS(t, `html[data-theme="${t.id}"]`)).join("\n\n");
  document.head.appendChild(st);

  // ---------------------------------------------------------------- state
  const q = new URLSearchParams(location.search);
  const pick = (k, ok, dflt) => { const v = q.get(k) || ls.get("lab:" + k); return ok(v) ? v : dflt; };
  const state = {
    theme: pick("theme", v => !!byId(v), "earth"),
    layout: pick("layout", v => L.LAYOUTS.some(l => l.id === v), "sidebar"),
    mode: null,
  };
  state.mode = pick("mode", v => ["light", "dark", "auto"].includes(v), byId(state.theme).defaultMode || "auto");
  { const m0 = q.get("mode") || ls.get("lab:mode"); if (["light", "dark", "auto"].includes(m0)) state.userMode = m0; }   // an explicit choice carries across themes
  L.state = state;
  L.apply = function (patch = {}, opts = {}) {
    Object.assign(state, patch);
    const t = byId(state.theme), ms = L.modes(t);
    let mode = state.mode;
    if (ms.length === 1) mode = ms[0];                     // single-appearance theme: fixed
    const h = document.documentElement;
    h.dataset.theme = t.id; h.dataset.layout = state.layout; h.dataset.mode = mode;
    // browser chrome colour follows the theme
    const dark = mode === "dark" || (mode === "auto" && matchMedia("(prefers-color-scheme: dark)").matches);
    const tk = (dark && t.dark) || t.light || t.dark;
    document.querySelectorAll('meta[name="theme-color"]').forEach(m => m.setAttribute("content", tk.bg));
    if (!opts.silent) {
      ["theme", "layout", "mode"].forEach(k => ls.set("lab:" + k, state[k]));
      const u = new URL(location.href);
      u.searchParams.set("theme", state.theme); u.searchParams.set("layout", state.layout);
      if (ms.length > 1) u.searchParams.set("mode", state.mode); else u.searchParams.delete("mode");
      try { history.replaceState(history.state, "", u.pathname + u.search + location.hash); } catch (e) { }
    }
    document.dispatchEvent(new CustomEvent("lab:change", { detail: { ...state, effectiveMode: mode, dark } }));
  };
  L.apply({}, { silent: !q.has("theme") && !ls.get("lab:theme") });
  matchMedia("(prefers-color-scheme: dark)").addEventListener("change", () => L.apply({}, { silent: true }));

  // ---------------------------------------------------------------- the lab only wires one page
  const ALLOWED = new RegExp(`^#/${EV}/dash/${TS}(/[a-z0-9]*)?$`, "i");
  L.allowed = h => ALLOWED.test(h);
  if (!L.allowed(location.hash)) { try { history.replaceState(null, "", location.pathname + location.search + HOME); } catch (e) { location.hash = HOME; } }
  let lastOk = location.hash;
  addEventListener("hashchange", e => {
    if (L.allowed(location.hash)) { lastOk = location.hash; return; }
    e.stopImmediatePropagation();                         // registered before app.js, so the router never sees it
    try { history.replaceState(null, "", location.pathname + location.search + lastOk); } catch (x) { }
    const sel = document.getElementById("tcsel"); if (sel) sel.value = TS;
    L.toast && L.toast("Lab preview: only the Dashboard at Sun 09:00 is wired up.");
  });
})();
